export const translate = (text, lang) =>
  lang === "en" ? (TEXT[text] ?? text) : text;
export function bindStaticTranslations(root = document) {
  const entries = [];
  const walker = document.createTreeWalker(root.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    const key = node.textContent.trim().replace(/\s+/g, " ");
    if (Object.hasOwn(TEXT, key)) entries.push({ node, key });
  }
  for (const el of root.querySelectorAll("[placeholder],[aria-label]"))
    for (const attr of ["placeholder", "aria-label"]) {
      const key = el.getAttribute(attr);
      if (key && Object.hasOwn(TEXT, key)) entries.push({ el, attr, key });
    }
  return (lang) => {
    for (const entry of entries) {
      const value = translate(entry.key, lang);
      if (entry.node) entry.node.textContent = value;
      else entry.el.setAttribute(entry.attr, value);
    }
    document.documentElement.lang = lang === "en" ? "en" : "pt-BR";
    document.title =
      lang === "en"
        ? "Notícias Hub · Your professional radar"
        : "Notícias Hub · Seu radar profissional";
  };
}
